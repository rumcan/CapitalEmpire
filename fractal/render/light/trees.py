"""render.light.trees: the side each library tree is lit from (tree-sun.ts TREE_LIGHT, generated), described; the engine mirrors the left-lit ones."""
from fractal.holon import Fn, Holon

HOLON = Holon(
    id="render.light.trees", rung=3, title="Tree light side",
    purpose="Say, for every library tree, which side its picture is lit from, so the mirrored ones carry their light from the right.",
    requires=[
        "TREE_MIRROR is the trees whose light is on the left: they are drawn mirrored (tree-sun.ts line 294).",
        "tests/tree-sun.test.ts fails while a library tree is missing from TREE_LIGHT (regenerated by scripts/assets/tree-sun.mjs).",
    ],
    owns=["TREE_LIGHT (id to 'left' or 'right')"],
    files=["src/game/tree-sun.ts"],
    dynamics=[
        Fn(name="TREE_MIRROR", at="src/game/tree-sun.ts:294", does="the set of trees drawn mirrored (lit from the left)", sig="TREE_MIRROR: ReadonlySet<string>"),
        Fn(name="TREE_LIGHT", at="src/game/tree-sun.ts:8", does="the lit side of each tree picture, by id", sig="TREE_LIGHT: Record<string, 'left' | 'right'>"),
    ],
    inputs=["a tree's library id"],
    outputs=["flip for the tree (engine.ts addProp and treeSprites)"],
    tests=["tests/tree-sun.test.ts", "tests/farm-crops.test.ts", "tests/newart.test.ts"],
    below=["art.library.plants"], above=["render.light", "core.engine.orchestra"],
    dual=None,
    rules=["never mirror lit sprites (trees lit from the left are the one owner-approved exception, see requires)"],
    impl="describe",
)
