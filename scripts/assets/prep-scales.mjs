// The owner's scale table (places-v5 scales.json on TrickOrTreat branch town/builder-in-repo), kept for the library ids the
// game has: writes src/game/lots/scales.ts (OWNER_SCALE: id -> the scale field, REMOVED_IDS: the sprites the owner removed).
//   node scripts/assets/prep-scales.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, fromBranch } from './source.mjs';

const OUT = path.join(ROOT, 'src/game/lots/scales.ts');
import { SCALE_OVERRIDES } from './overrides.mjs';
import { readRemoved } from './removed.mjs';
const table = JSON.parse(Buffer.from(await fromBranch('town/builder-in-repo', 'scripts/town-builder/places-v5/scales.json')).toString('utf8'));
const lib = fs.readFileSync(path.join(ROOT, 'src/game/library.ts'), 'utf8');
// Supplemental sprites are appended at runtime, so their IDs are in the imported libraries rather than inline here.
const sources = [lib, ...[...lib.matchAll(/import \{ append\w+ \} from '\.\/([^']+)';/g)].map(m => fs.readFileSync(path.join(ROOT, 'src/game', `${m[1]}.ts`), 'utf8'))];
const ids = [...new Set(sources.flatMap(src => [...src.matchAll(/"id":"([^"]+)"/g)].map(m => m[1])))].sort();
const out = [];
for (const id of ids) { const s = SCALE_OVERRIDES[id] ?? table[id]?.scale; if (typeof s === 'number') out.push([id, +s.toFixed(3)]); }
fs.mkdirSync(path.dirname(OUT), { recursive: true });
// the removed sprites (removed.json), so the appended libraries (cars, east, businesses) skip them at runtime too
const removed = Object.keys(readRemoved()).sort();
fs.writeFileSync(OUT, `// Generated by scripts/assets/prep-scales.mjs from the owner's scale table (places-v5/scales.json). Do not edit.\nexport const OWNER_SCALE: Record<string, number> = {\n${out.map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join('\n')}\n};\nexport const REMOVED_IDS: string[] = [${removed.map(id => `\n  ${JSON.stringify(id)},`).join('')}\n];\n`);
console.log(`scales: ${out.length} of ${ids.length} library ids written to src/game/lots/scales.ts; ${removed.length} removed ids`);
