// The owner's scale table (places-v5 scales.json on TrickOrTreat branch town/builder-in-repo), kept for the library ids the
// game has: writes src/game/lots/scales.ts (OWNER_SCALE: id -> the scale field).
//   node scripts/assets/prep-scales.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, fromBranch } from './source.mjs';

const OUT = path.join(ROOT, 'src/game/lots/scales.ts');
const table = JSON.parse(Buffer.from(await fromBranch('town/builder-in-repo', 'scripts/town-builder/places-v5/scales.json')).toString('utf8'));
const lib = fs.readFileSync(path.join(ROOT, 'src/game/library.ts'), 'utf8');
const ids = [...new Set([...lib.matchAll(/"id":"([^"]+)"/g)].map(m => m[1]))].sort();
const out = [];
for (const id of ids) { const s = table[id]; if (s && typeof s.scale === 'number') out.push([id, +s.scale.toFixed(3)]); }
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `// Generated by scripts/assets/prep-scales.mjs from the owner's scale table (places-v5/scales.json). Do not edit.\nexport const OWNER_SCALE: Record<string, number> = {\n${out.map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join('\n')}\n};\n`);
console.log(`scales: ${out.length} of ${ids.length} library ids written to src/game/lots/scales.ts`);
