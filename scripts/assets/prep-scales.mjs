// The owner's scale table (places-v5 scales.json on TrickOrTreat branch town/builder-in-repo), kept for the library ids the
// game has: writes src/game/lots/scales.ts (OWNER_SCALE: id -> the scale field, REMOVED_IDS: the sprites the owner removed).
//   node scripts/assets/prep-scales.mjs
// The studio's sizes (scripts/assets/scale-overrides.json) are baked into OWNER_SCALE as they are when this runs, and scales.ts also imports the
// file itself, so a size set or reset in the studio since shows in the game after a reload, with no rebuild: a size set replaces the baked one,
// a size reset falls back to the table's (TABLE_OF_RESIZED, src/game/lots/studio-base.ts: the table's scale of every id the studio had resized).
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, fromBranch } from './source.mjs';

const OUT = path.join(ROOT, 'src/game/lots/scales.ts'), BASE = path.join(ROOT, 'src/game/lots/studio-base.ts');
import { SCALE_OVERRIDES } from './overrides.mjs';
import { readRemoved } from './removed.mjs';
const table = JSON.parse(Buffer.from(await fromBranch('town/builder-in-repo', 'scripts/town-builder/places-v5/scales.json')).toString('utf8'));
const lib = fs.readFileSync(path.join(ROOT, 'src/game/library.ts'), 'utf8');
// Supplemental sprites are appended at runtime, so their IDs are in the imported libraries rather than inline here.
const sources = [lib, ...[...lib.matchAll(/import \{ append\w+ \} from '\.\/([^']+)';/g)].map(m => fs.readFileSync(path.join(ROOT, 'src/game', `${m[1]}.ts`), 'utf8'))];
const ids = [...new Set(sources.flatMap(src => [...src.matchAll(/"id":"([^"]+)"/g)].map(m => m[1])))].sort();
const out = [], base = [];
for (const id of ids) {
  const t = table[id]?.scale, s = SCALE_OVERRIDES[id] ?? t;
  if (typeof s === 'number') out.push([id, +s.toFixed(3)]);
  if (SCALE_OVERRIDES[id] !== undefined) base.push([id, typeof t === 'number' ? +t.toFixed(3) : null]);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
// the removed sprites (removed.json), so the appended libraries (cars, east, businesses) skip them at runtime too
const removed = Object.keys(readRemoved()).sort();
fs.writeFileSync(OUT, `// Generated by scripts/assets/prep-scales.mjs from the owner's scale table (places-v5/scales.json). Do not edit.
import STUDIO from '../../../scripts/assets/scale-overrides.json';
import { TABLE_OF_RESIZED } from './studio-base';
export const OWNER_SCALE: Record<string, number> = {\n${out.map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join('\n')}\n};
export const REMOVED_IDS: string[] = [${removed.map(id => `\n  ${JSON.stringify(id)},`).join('')}\n];
/** the sizes set in the sprite studio (scripts/assets/scale-overrides.json: id -> the scale it is drawn at wherever it is placed), read at runtime */
export const STUDIO_SCALE: Readonly<Record<string, number>> = STUDIO;
/** the owner's table scale of each library id that has one: what a studio size falls back to when it is reset */
export const TABLE_SCALE: Readonly<Record<string, number>> = Object.fromEntries(Object.entries({ ...OWNER_SCALE, ...TABLE_OF_RESIZED }).filter((e): e is [string, number] => e[1] !== null));
// the studio's sizes now (a dev reload shows a studio change, no rebuild): a size reset since this was generated falls back to the table's (or
// to none), a size set since replaces the baked one
for (const [id, s] of Object.entries(TABLE_OF_RESIZED)) if (!(id in STUDIO)) { if (s === null) delete OWNER_SCALE[id]; else OWNER_SCALE[id] = s; }
Object.assign(OWNER_SCALE, STUDIO);
`);
fs.writeFileSync(BASE, `// Generated by scripts/assets/prep-scales.mjs. Do not edit.
/** the owner's table scale (places-v5/scales.json; null: none) of every id the sprite studio had resized when scales.ts was generated, so a size
 *  reset in the studio since falls back to it at runtime (scales.ts) */
export const TABLE_OF_RESIZED: Readonly<Record<string, number | null>> = {\n${base.map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join('\n')}\n};
`);
console.log(`scales: ${out.length} of ${ids.length} library ids written to src/game/lots/scales.ts (${base.length} resized in the studio); ${removed.length} removed ids`);
