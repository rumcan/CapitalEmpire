// Nature patches: large flat compositions of the builder's ground decals (grass, weeds, moss, leaf drifts, dirt, pinecones,
// twigs), each baked into one picture that the ground painter scatters over open grass to break up its uniformity.
// Every patch follows its kind's recipe: the decals thick at the centre and thinning to the edge, the big pieces first.
//   node scripts/assets/nature-patches.mjs   -> src/assets/ground/nature.webp, src/game/nature-patches.ts
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { LIB, render, toScreen } from './lot-render.mjs';
import { SCENARIOS, rng } from './lot-layout.mjs';
import { ROOT } from './source.mjs';

/** the patch kinds: [scenario or id list, count per 100 m2, scale range] in drawing order */
const KINDS = {
  leafy: [['bareYard', 0.3, [0.6, 0.9]], ['lawn', 3, [0.5, 0.8]], ['fenceLeaves', 4, [0.7, 1.2]], ['treeLeaves', 6, [0.5, 0.9]], ['houseLeaves', 3, [0.8, 1.2]], ['deadwood', 0.6, [0.7, 1.0]]],
  wild: [['lawn', 9, [0.6, 1.0]], ['treeLeaves', 1.5, [0.4, 0.7]], ['muddyGate', 0.5, [0.8, 1.1]]],
  mossy: [['lawn', 5, [0.6, 0.9]], ['pineFloor', 4, [0.7, 1.1]], ['deadwood', 2, [0.7, 1.0]], ['fenceLeaves', 1.5, [0.6, 0.9]]],
  bare: [['bareYard', 1.2, [0.7, 1.1]], ['playWear', 2, [0.8, 1.2]], ['muddyGate', 1.5, [0.8, 1.2]], ['treeLeaves', 2, [0.5, 0.8]], ['puddle', 0.3, [0.7, 1.0]]],
  golden: [['lawn', 6, [0.6, 1.0]], ['treeLeaves', 5, [0.5, 0.9]], ['fenceLeaves', 2, [0.7, 1.1]]],
};
/** the variants baked: kind and seed; each about PATCH_M metres across */
export const PATCH_M = 16;
const VARIANTS = [['leafy', 1], ['leafy', 2], ['wild', 3], ['wild', 4], ['mossy', 5], ['mossy', 6], ['bare', 7], ['golden', 8], ['golden', 9], ['leafy', 10]];
/** px per native px the patches are stored at (the ground's closest cache level is 0.6 screen px per world px) */
const RES = 0.6;

/** one patch: decals in a disc of radius R (metres) around (R, R), dense at the centre (radius drawn as sqrt(u) * R * f) */
export function patch(kind, seed) {
  const r = rng(seed), R = PATCH_M / 2, out = [], area = Math.PI * R * R;
  const have = ids => ids.filter(id => { const i = LIB.get(id); return i && !i.hidden; });
  for (const [sc, per100, [s0, s1]] of KINDS[kind]) {
    const ids = have(SCENARIOS[sc] ?? [sc]); if (!ids.length) continue;
    for (let k = 0, n = Math.round(per100 * area / 100 * (0.8 + 0.4 * r())); k < n; k++) {
      const a = r() * Math.PI * 2, d = Math.sqrt(r()) * R * (0.45 + 0.55 * r());
      out.push({ id: ids[Math.floor(r() * ids.length)], x: R + Math.cos(a) * d, y: R + Math.sin(a) * d, flip: r() < 0.5, scale: s0 + (s1 - s0) * r(), z: out.length });
    }
  }
  return out;
}

if (process.argv[1] && import.meta.url === (await import('node:url')).pathToFileURL(path.resolve(process.argv[1])).href) {
  const tiles = [], meta = []; let x = 0, H = 0;
  for (const [kind, seed] of VARIANTS) {
    const items = patch(kind, seed), c = [toScreen(0, 0), toScreen(PATCH_M, 0), toScreen(0, PATCH_M), toScreen(PATCH_M, PATCH_M)];
    const box = [Math.min(...c.map(p => p[0])) - 140, Math.min(...c.map(p => p[1])) - 90, Math.max(...c.map(p => p[0])) + 140, Math.max(...c.map(p => p[1])) + 90];
    const png = await render(items, box, RES, { shadows: false });
    const { data, info } = await sharp(png).raw().toBuffer({ resolveWithObject: true });
    let x0 = info.width, y0 = info.height, x1 = -1, y1 = -1;
    for (let yy = 0; yy < info.height; yy++) for (let xx = 0; xx < info.width; xx++) if (data[(yy * info.width + xx) * 4 + 3] > 2) { x0 = Math.min(x0, xx); x1 = Math.max(x1, xx); y0 = Math.min(y0, yy); y1 = Math.max(y1, yy); }
    const w = x1 - x0 + 1, h = y1 - y0 + 1, [cx, cy] = toScreen(PATCH_M / 2, PATCH_M / 2);
    tiles.push({ input: await sharp(png).extract({ left: x0, top: y0, width: w, height: h }).png().toBuffer(), left: x + 1, top: 1 });
    // ox, oy: the patch centre inside its rectangle, in world px at scale 1
    meta.push({ kind, x: x + 1, y: 1, w, h, ox: +((cx - box[0]) - x0 / RES).toFixed(1), oy: +((cy - box[1]) - y0 / RES).toFixed(1) });
    x += w + 2; H = Math.max(H, h + 2);
    console.log(kind, seed, items.length, 'decals', `${w}x${h}`);
  }
  await sharp({ create: { width: x, height: H, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } }).composite(tiles).webp({ quality: 88, alphaQuality: 95, effort: 6 }).toFile(path.join(ROOT, 'src/assets/ground/nature.webp'));
  fs.writeFileSync(path.join(ROOT, 'src/game/nature-patches.ts'), `// Generated by scripts/assets/nature-patches.mjs (the builder's ground decals composed into patches). Do not edit.
/** px per world px the patches are stored at */
export const NATURE_RES = ${RES};
/** a patch in nature.webp: its rectangle (px), kind, and its centre inside the rectangle (world px at scale 1) */
export const NATURE: { kind: string; x: number; y: number; w: number; h: number; ox: number; oy: number }[] = ${JSON.stringify(meta)};
`);
  console.log('nature patches', meta.length, `${x}x${H}`);
}
