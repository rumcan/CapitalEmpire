// Rebuild the supplemental car page from the checked-in eight-direction source PNGs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { readScales } from './overrides.mjs';
import { carModelSize } from '../../src/game/ext/car-art/model.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const out = path.join(root, 'src/assets/cars');
fs.mkdirSync(out, { recursive: true });
const models = ['burgundy-wagon', 'navy-wood-panel-wagon'];
const dirs = ['SE', 'S', 'SW', 'W', 'NW', 'N', 'NE', 'E'];
// a car is drawn at its owner size x CAR_SCALE (src/game/ext/car-art, read as the size report reads it); the owner's size is keyed by its model
// (scale-overrides.json, carModelSize: every heading is packed at the model's size; 1 when unset). Its cell is 512 px with a 16 px gutter each side
const sizes = readScales(), CAR_SCALE = +(/export const CAR_SCALE = ([\d.]+)/.exec(fs.readFileSync(path.join(root, 'src/game/ext/car-art/index.ts'), 'utf8'))?.[1] ?? 1);
const CELL = 512 - 32;
const items = [], composite = [];
for (const [modelIndex, model] of models.entries()) {
  const dir = path.join(root, 'art/cars', model);
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
  for (const [heading, key] of dirs.entries()) {
    const view = manifest.views.find(v => v.key === key), a = heading * Math.PI / 4, c = Math.cos(a), s = Math.sin(a);
    // Match one physical vehicle in every view. Native projection is 64 x 32 px per world tile (2 m).
    const w = 64 * (2.25 * Math.abs(c - s) + 0.9 * Math.abs(s + c));
    const groundH = 32 * (2.25 * Math.abs(c + s) + 0.9 * Math.abs(c - s));
    const ratio = w / view.width, h = view.height * ratio;
    // packed at 0.6 x its largest drawn size (the owner's size x CAR_SCALE, +5% jitter), as far as 3x its source's width and its cell go (upscaled past its pixels, softer)
    const want = 0.6 * Math.max(1, (carModelSize(sizes, `cars:${model}`) ?? 1) * CAR_SCALE * 1.05), fit = Math.min(want, 3 * view.width / w, CELL / w, CELL / h);
    if (fit < want * (1 - 1e-9)) console.warn(`${model} ${key}: packed at x${(fit / 0.6).toFixed(2)} of its size, capped by ${fit === 3 * view.width / w ? 'its 3x source' : 'its 512 px cell'}`);
    const width = Math.round(w * fit), height = Math.round(h * fit);
    const cell = modelIndex * 8 + heading, left = (cell % 4) * 512 + 16, top = Math.floor(cell / 4) * 512 + 16;
    composite.push({ input: await sharp(path.join(dir, view.file)).resize(width, height, { kernel: 'lanczos3' }).sharpen({ sigma: 0.6 }).png().toBuffer(), left, top });
    const hx = 2.25 * Math.abs(c) + 0.9 * Math.abs(s), hy = 2.25 * Math.abs(s) + 0.9 * Math.abs(c);
    items.push({ id: `cars:${model}:${key}`, name: `${model.replaceAll('-', ' ')} ${key}`, cat: 'Vehicles', kind: 'car', w, h, ax: w / 2, ay: h - groundH / 2, boxes: [{ hx, hy, dx: 0, dy: 0 }], solid: 2, big: true, door: false, cost: 6300, tex: [0, left / 2048, top / 2048, (left + width) / 2048, (top + height) / 2048], quad: [0, 0, w, h] });
  }
}
const full = await sharp({ create: { width: 2048, height: 2048, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } }).composite(composite).png().toBuffer();
for (let m = 0; m < 5; m++) await sharp(full).resize(2048 >> m, 2048 >> m).webp({ quality: 92, alphaQuality: 100 }).toFile(path.join(out, `cars-${m}.webp`));
fs.writeFileSync(path.join(root, 'src/game/cars-library.ts'), [
  '// Generated by scripts/assets/prep-cars.mjs. Source images are retained in art/cars.',
  "import type { LibItem } from './types';",
  "import { REMOVED_IDS } from './lots/scales';",
  "const removed = new Set(REMOVED_IDS);",
  ...Array.from({ length: 5 }, (_, m) => `import m${m} from '../assets/cars/cars-${m}.webp';`),
  `const ITEMS: LibItem[] = ${JSON.stringify(items)};`,
  '/** Append after the base library/walker frames, preserving every existing saved item index. */',
  'export function appendCars(library: LibItem[], pages: string[][]) {',
  '  const page = pages.length; pages.push([m0, m1, m2, m3, m4]);',
  '  for (const item of ITEMS) if (!removed.has(item.id)) library.push({ ...item, tex: [page, ...item.tex.slice(1)] as LibItem["tex"] });',
  '}', ''
].join('\n'));
console.log(`Prepared ${items.length} directional car sprites on one supplemental atlas page.`);
