// Which tree sprites are lit from the left: the game's sun comes from the right (screen upper right), so those trees are always drawn
// mirrored and every other tree never is (no random mirroring anywhere: engine.addProp and treeSprites apply TREE_MIRROR).
//   node scripts/assets/tree-sun.mjs
// The side is measured on the mip-0 atlas picture: the brightness of each opaque pixel against its distance from the tree's centre line,
// so a crown brighter on its left scores negative. Writes src/game/tree-sun.ts and output/tree-sun/contact.png (each tree as it will be
// drawn, its score under it) to check by eye. TREE_SIDE overrides a reading by hand when the measure is fooled.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const REVIEW = path.join(root, 'output/tree-sun');
/** hand readings that win over the measure: id -> 'left' | 'right' (the side the light comes from in the art) */
const TREE_SIDE = {};

// every tree in a generated library: its atlas page (mip 0) and rectangle
const trees = [];
for (const f of ['library', 'east-library', 'business-library', 'construction-library', 'golf-library', 'cars-library', 'views-library', 'trees-library']) {
  const text = fs.readFileSync(path.join(root, `src/game/${f}.ts`), 'utf8');
  const imports = new Map([...text.matchAll(/import\s+(\w+)\s+from\s+'([^']+\.webp)'/g)].map(m => [m[1], path.join(root, 'src/game', m[2])]));
  const pagesLiteral = /ATLAS_PAGES: string\[\]\[\] = (\[.*?\]);/.exec(text)?.[1] ?? /const PAGES: string\[\]\[\] = (\[.*?\]);/.exec(text)?.[1];
  const pages = pagesLiteral ? [...pagesLiteral.matchAll(/\[(\w+)/g)].map(m => imports.get(m[1])) : [...imports].filter(([a]) => /m0$/.test(a)).map(([, p]) => p);
  for (const m of text.matchAll(/\{"id":"([^"]+)","name":"[^"]*","cat":"[^"]*","kind":"tree".*?"tex":\[([^\]]+)\]/g)) {
    const [page, u0, v0, u1, v1] = m[2].split(',').map(Number);
    if (!pages[page]) throw new Error(`${m[1]}: no page ${page} in ${f}`);
    trees.push({ id: m[1], file: pages[page], u0, v0, u1, v1 });
  }
}

fs.mkdirSync(REVIEW, { recursive: true });
const mirror = [], tiles = [];
for (const t of trees) {
  const { width: PW, height: PH } = await sharp(t.file).metadata();
  const left = Math.round(t.u0 * PW), top = Math.round(t.v0 * PH), width = Math.round((t.u1 - t.u0) * PW), height = Math.round((t.v1 - t.v0) * PH);
  const png = await sharp(t.file).extract({ left, top, width, height }).png().toBuffer();
  const { data } = await sharp(png).raw().toBuffer({ resolveWithObject: true });
  // the crown only (the top 70%: the trunk and its shadow would pull the reading), opaque pixels
  let n = 0, sx = 0, sl = 0;
  const px = [];
  for (let y = 0; y < height * 0.7; y++) for (let x = 0; x < width; x++) {
    const i = (y * width + x) * 4; if (data[i + 3] < 200) continue;
    const l = 0.3 * data[i] + 0.59 * data[i + 1] + 0.11 * data[i + 2]; px.push([x, l]); n++; sx += x; sl += l;
  }
  const cx = sx / n, ml = sl / n;
  let cov = 0, vx = 0; for (const [x, l] of px) { cov += (x - cx) * (l - ml); vx += (x - cx) ** 2; }
  t.score = cov / Math.sqrt(vx * n) / Math.max(1, ml) * 100; // brightness slope across the crown, in % of its mean brightness
  t.side = TREE_SIDE[t.id] ?? (t.score >= 0 ? 'right' : 'left');
  if (t.side === 'left') mirror.push(t.id);
  // the review tile: the tree as the game will draw it
  const thumb = await sharp(png).flop(t.side === 'left').resize(160, 200, { fit: 'inside' }).png().toBuffer(), meta = await sharp(thumb).metadata();
  const label = `<svg xmlns="http://www.w3.org/2000/svg" width="180" height="44"><text x="90" y="16" text-anchor="middle" font-size="11" fill="#172a32" font-family="sans-serif">${t.id.replace(/^(capital|world|ref):/, '')}</text><text x="90" y="34" text-anchor="middle" font-size="11" fill="${t.side === 'left' ? '#c0392b' : '#172a32'}" font-family="sans-serif">${t.score.toFixed(1)} ${t.side === 'left' ? 'lit left: mirrored' : 'lit right'}${TREE_SIDE[t.id] ? ' (by hand)' : ''}</text></svg>`;
  tiles.push([{ input: thumb, left: Math.floor((180 - meta.width) / 2), top: 200 - meta.height }, { input: Buffer.from(label), left: 0, top: 200 }]);
}
const cols = 8, rows = Math.ceil(tiles.length / cols);
await sharp({ create: { width: cols * 180, height: rows * 250, channels: 4, background: '#d8e0e3' } })
  .composite(tiles.flatMap((t, i) => t.map(c => ({ ...c, left: c.left + (i % cols) * 180, top: c.top + Math.floor(i / cols) * 250 }))))
  .png().toFile(path.join(REVIEW, 'contact.png'));
fs.writeFileSync(path.join(root, 'src/game/tree-sun.ts'), [
  '// Generated by scripts/assets/tree-sun.mjs: the tree art lit from the left. The sun comes from the right, so these trees are always drawn',
  '// mirrored and every other tree never is: no tree is mirrored at random (engine.addProp and treeSprites).',
  `export const TREE_MIRROR: ReadonlySet<string> = new Set(${JSON.stringify(mirror.sort())});`, ''].join('\n'));
console.log(trees.map(t => `${t.id} ${t.score.toFixed(1)} ${t.side}`).join('\n'));
console.log(`${trees.length} trees, ${mirror.length} lit from the left (mirrored); review: ${path.relative(root, REVIEW)}/contact.png`);
