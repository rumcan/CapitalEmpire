// Pack the town builder's flat ground decals (leaf drifts, worn grass, litter, oil stains, mud tracks) that the Lot Composer
// lays in yards, drives and car parks, into one strip for the ground painter. Read from the local TrickOrTreat builder library
// (read only; items the owner hid there are left out). Writes src/assets/ground/lot-decals.webp and src/game/lot-decals.ts.
// A decal the owner resized in the sprite studio (scale-overrides.json, default 1) is packed at that scale: w and h are the game size.
//   node scripts/assets/prep-decals.mjs
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { ROOT, TOT } from './source.mjs';
import { REMOVED } from './removed.mjs';
import { readScales } from './overrides.mjs';

/** the decals the composer uses, by group (the group names are what compose.ts asks for) */
const GROUPS = {
  leaves: ['decal:decal-06-orange-leaf-scatter', 'decal:decal-07-red-leaf-cluster', 'decal:decal-08-yellow-leaf-scatter', 'decal:scatter-tiny-leaves', 'gen:drift-1', 'gen:drift-2', 'gen:drift-3', 'gen:drift-4', 'gen:drift-5', 'gen:drift-6', 'gen:drift-7', 'gen:drift-8', 'town:leaf_drift'],
  worn: ['town:bare_grass', 'town:mud_grass'],
  litter: ['town:paper_litter', 'town:bag_litter', 'gen:litter-candy', 'gen:litter-fastfood', 'gen:litter-newspaper', 'poi:newspaper-cup-litter', 'poi:candy-soda-litter', 'expansion:can-litter'],
  rubbish: ['gen:rubbish-bags', 'gen:rubbish-cardboard'],
  woods: ['gen:pinecones-needles', 'gen:twigs-branches'],
  tufts: ['decal:scatter-grass-tufts', 'decal:decal-01-lush-grass', 'decal:decal-02-dry-golden-grass', 'decal:decal-03-moss-groundcover', 'decal:decal-04-low-weeds', 'decal:decal-05-thin-grass'],
  stain: ['town:oil_stain', 'town:paving_wear', 'town:wheel_wear', 'expansion:paint-spill'],
  gravel: ['town:gravel_spill', 'gen:gravel-spill'],
  mud: ['expansion:mud-tracks-x', 'expansion:mud-tracks-y', 'expansion:mud-footprints', 'expansion:mud-arc'],
};
const dir = path.join(TOT, 'output/town-builder/library'), file = path.join(dir, 'library.json');
if (!fs.existsSync(file)) { console.error(`no TrickOrTreat library at ${file}: the lot decals stay as they are`); process.exit(1); }
const items = JSON.parse(fs.readFileSync(file, 'utf8')).items, byId = new Map(items.map(i => [i.id, i]));
// every recoloured variation of a group's decal joins its group (the 2026-10-17 run: litter, grass and leaf variants), so the lots get more variety
for (const ids of Object.values(GROUPS)) for (const it of items) { const of = (it.tags || []).find(t => t.startsWith('variation-of:'))?.slice(13); if (of && ids.includes(of) && !ids.includes(it.id)) ids.push(it.id); }
const scales = readScales();

const PAGE_W = 2048, GAP = 2, tiles = [], meta = [];
let x = 0, y = 0, rowH = 0;
for (const [group, ids] of Object.entries(GROUPS)) for (const id of ids) {
  const it = byId.get(id);
  if (!it || it.hidden || !it.flat || REMOVED.has(id) || !fs.existsSync(path.join(dir, it.file))) { console.warn('skip', id); continue; }
  const s = scales[id] ?? 1, w = Math.max(1, Math.round(Math.round(it.w) * s)), h = Math.max(1, Math.round(Math.round(it.h) * s));
  if (x + w + GAP > PAGE_W) { x = 0; y += rowH + GAP; rowH = 0; }
  tiles.push({ input: await sharp(path.join(dir, it.file)).resize(w, h, { fit: 'fill', kernel: 'lanczos3' }).png().toBuffer(), left: x + 1, top: y + 1 });
  meta.push({ id, group, x: x + 1, y: y + 1, w, h });
  x += w + GAP; rowH = Math.max(rowH, h);
}
const H = y + rowH + GAP;
await sharp({ create: { width: PAGE_W, height: H, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } }).composite(tiles)
  .webp({ quality: 90, alphaQuality: 100, effort: 6 }).toFile(path.join(ROOT, 'src/assets/ground/lot-decals.webp'));
fs.writeFileSync(path.join(ROOT, 'src/game/lot-decals.ts'), `// Generated by scripts/assets/prep-decals.mjs from the TrickOrTreat town builder library's flat decals. Do not edit.
/** a flat ground decal in lot-decals.webp: its rectangle (px = world px at scale 1, drawn centred on its ground point) and group */
export interface LotDecal { id: string; group: string; x: number; y: number; w: number; h: number }
export const LOT_DECALS: LotDecal[] = [
${meta.map(m => '  ' + JSON.stringify(m) + ',').join('\n')}
];
`);
console.log(`lot decals: ${meta.length} in a ${PAGE_W} x ${H} strip`);
