"""Download a curated set of Maple Falls town-builder sprites (from the public game export in the
rumcan/TrickOrTreat repo), downscale them to 50% and generate src/game/library.ts with their metadata."""
import json, subprocess, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.makedirs('/tmp/tot', exist_ok=True)
if not os.path.exists('/tmp/tot/town.json'):
    subprocess.run(['curl', '-sL', '-o', '/tmp/tot/town.json', 'https://raw.githubusercontent.com/rumcan/TrickOrTreat/main/public/assets/town-built/town.json'], check=True)
d = json.load(open('/tmp/tot/town.json'))
items = d['items']
SEL = {
 'Houses': ['world:house_1','world:house_3','world:house_4','gen:house-duplex','gen:house-l-ranch','gen:house-ranch-long','gen:house-splitlevel','gen:house-l-shape','gen:house-farmhouse-wrap','static:garage_timber','static:garage_brick'],
 'Shops & services': ['town:bakery','town:grocery','town:pharmacy','town:laundromat','town:postoffice','town:firestation','town:fish_tackle','world:diner','world:arcade','world:video_rental','ref:building-gas-canopy'],
 'Landmarks': ['world:church','world:gazebo','world:watertower','ref:landmark-windmill','world:barn','world:primary_school'],
 'Trees & plants': ['world:tree_oak_0','world:tree_oak_1','world:tree_oak_2','world:tree_pine_0','world:tree_pine_1','ref:tree-maple-crimson','ref:tree-birch-gold','ref:tree-spruce-blue','world:bush_0','world:bush_1','world:hedge','town:hydrangea'],
 'Vehicles': ['world:car_0','world:car_1','world:car_2','world:car_3','static:pickup_n','static:van_e','static:compact_e','static:compact_n','world:schoolbus'],
 'Street furniture': ['world:streetlamp','world:hydrant','world:mailbox','world:bench','world:trashcan','town:stop_sign','town:street_sign','town:traffic_light','town:bus_stop','town:phone_booth','town:utility_pole','town:bike_rack','town:picnic_table','town:planter_square'],
 'Halloween': ['world:pumpkin_0','world:pumpkin_1','world:scarecrow','ref:halloween-hay-bales','ref:halloween-pumpkin-cluster','world:candy_stand','gen:inflatable-pumpkin','ref:halloween-sheet-ghost'],
 'Fences': ['world:fence_picket_x','world:fence_picket_y','world:fence_iron_x','world:fence_iron_y','gen:fence-privacy-wood'],
 'Yard': ['gen:trash-cans-row','gen:kids-bikes','expansion:trampoline','expansion:doghouse','expansion:basketball-hoop','expansion:washing-line'],
}
COST = {'Houses':9000,'Shops & services':24000,'Landmarks':40000,'Trees & plants':250,'Vehicles':3500,'Street furniture':300,'Halloween':120,'Fences':90,'Yard':400}
out = []
imports = []
n = 0
os.makedirs(f'{ROOT}/src/assets/sprites', exist_ok=True)
for cat, ids in SEL.items():
    for id_ in ids:
        it = items[id_]
        fname = it['file'].split('/')[-1]
        src = f'https://raw.githubusercontent.com/rumcan/TrickOrTreat/main/public/assets/town-built/sprites/{fname}'
        dst = f'{ROOT}/src/assets/sprites/{fname}'
        if not os.path.exists(dst):
            subprocess.run(['curl','-sL','-o','/tmp/tot/dl.webp',src],check=True)
            subprocess.run(['convert','/tmp/tot/dl.webp','-resize','50%','-quality','80','-define','webp:method=6',dst],check=True)
        var = f'img{n}'; n += 1
        imports.append(f"import {var} from '../assets/sprites/{fname}';")
        base = COST[cat]
        area = sum(b['hx']*b['hy']*4 for b in it['boxes']) or 1
        cost = int(round(base * (0.6 + 0.4*min(3, area/(30 if base>5000 else 1))) / 10) * 10)
        entry = {
            'id': id_, 'name': it['name'], 'cat': cat, 'kind': it['kind'], 'w': it['w'], 'h': it['h'], 'ax': it['ax'], 'ay': it['ay'],
            'boxes': it['boxes'], 'solid': it['solid'], 'big': it['big'], 'door': bool(it.get('door')), 'cost': cost,
        }
        if it.get('glows'): entry['glows'] = it['glows']
        if it.get('doorAt'): entry['doorAt'] = it['doorAt']
        out.append((var, entry))
lines = ["// Generated by scripts/prep-sprites.py from the Maple Falls town export (rumcan/TrickOrTreat, public/assets/town-built/town.json).",
         "// w,h,ax,ay are display pixels at the native 128px-per-tile scale; boxes are footprints in metres (2 m per tile).",
         "import type { LibItem } from './types';", *imports, "", "export const LIBRARY: LibItem[] = ["]
for var, e in out:
    s = json.dumps(e, separators=(',',':'))
    s = s[:-1] + f',"src":{var}}}'
    lines.append('  ' + s + ',')
lines.append('];')
open(f'{ROOT}/src/game/library.ts','w').write('\n'.join(lines)+'\n')
print('items', len(out))
