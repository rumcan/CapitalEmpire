// T398 (#1070, PR 2): the owner's marks on pictures that a house lot never draws. The sprite studio's Library marks a picture "angles-wrong" (its angles are not the true
// quarter turns of the building), "more-angles" (not enough angles of it) or "redo-style" (the catch-all: look it over for every fault) in scripts/assets/review-flags.json;
// "turned-ok" (off for a normal view, good as a slightly turned straight-on one) is not a fault. The lot composer reads src/game/lots/flagged-views.ts, written here: a picture
// id -> its mark, for the three that bar a picture (the owner, 2026-11-09: "never use a view flagged angles-wrong, more-angles or redo-style": a cottage drawn on a map-axis
// road with a picture whose walls do not follow the lot's diamond).
//   node scripts/lots/flagged-views.mjs [--flags FILE]     writes src/game/lots/flagged-views.ts (default FILE: scripts/assets/review-flags.json)
//   node scripts/lots/flagged-views.mjs --check [--flags FILE]   exits 1 when the file differs from what FILE says
// The owner's newest marks live in the studio's checkout (E:/Repos/CapitalEmpire/worktrees/theme-consistency/scripts/assets/review-flags.json); pass them with --flags.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2), opt = k => { const i = args.indexOf(`--${k}`); return i >= 0 ? args[i + 1] : undefined; };
const flagsFile = path.resolve(opt('flags') ?? path.join(root, 'scripts/assets/review-flags.json'));
const out = path.join(root, 'src/game/lots/flagged-views.ts');
const BAR = ['angles-wrong', 'more-angles', 'redo-style'];
const text = fs.readFileSync(flagsFile, 'utf8'), flags = JSON.parse(text);
const sha = crypto.createHash('sha256').update(text).digest('hex');
const rows = Object.entries(flags).filter(([, v]) => BAR.includes(v.flag)).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const body = [
  '// Generated by scripts/lots/flagged-views.mjs from the owner\'s review marks (scripts/assets/review-flags.json): the pictures a house lot never draws (T398).',
  `// source ${path.basename(flagsFile)} (the marks of 2026-11-09 when made with --flags) sha256 ${sha}; ${rows.length} marked pictures (angles-wrong, more-angles, redo-style); turned-ok marks are not faults and are not listed.`,
  'export type ViewMark = \'angles-wrong\' | \'more-angles\' | \'redo-style\';',
  '/** a picture id (a card\'s main picture, or view:<id>:se|sw|nw|n|e|s|w) -> the owner\'s mark on it */',
  'export const FLAGGED_VIEWS: Readonly<Record<string, ViewMark>> = {',
  ...rows.map(([id, v]) => `  ${JSON.stringify(id)}: ${JSON.stringify(v.flag)},`),
  '};',
  '/** the owner\'s mark on a picture, or null */',
  'export const markOf = (id: string): ViewMark | null => FLAGGED_VIEWS[id] ?? null;',
  '',
].join('\n');
if (args.includes('--check')) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (have !== body) { console.error('src/game/lots/flagged-views.ts differs from the review flags: run node scripts/lots/flagged-views.mjs'); process.exit(1); }
  console.log(`flagged-views.ts is current: ${rows.length} marked pictures`);
} else { fs.writeFileSync(out, body); console.log(`wrote ${path.relative(root, out)}: ${rows.length} marked pictures (source sha256 ${sha.slice(0, 12)})`); }
