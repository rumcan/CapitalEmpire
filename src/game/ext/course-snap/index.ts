// SimGolf-Plus modular course piece, spline ribbon, fat dimensional borders, sun-on-right bevel lighting, and 3D height/prop stamp maths (UIX revamp T029, Owner choice 3A).
// Pure TypeScript, no DOM globals, deterministic. Units: world coordinates, lengths, and widths in tiles of 2 m; angles in degrees; heights in m.

/** piece family kinds supported by the click-to-place and spline snap brush */
export type SnapPieceKind = 'fairway' | 'green' | 'tee' | 'bunker' | 'water' | 'path' | 'road';

/** specific SimGolf-Plus modular piece archetypes matching the course builder reference sheet */
export type CoursePieceArchetype =
  | 'green-kidney' | 'green-peanut' | 'green-practice'
  | 'tee-raised' | 'tee-box'
  | 'fairway-corridor' | 'fairway-pear' | 'fairway-dogleg-left' | 'fairway-dogleg-right'
  | 'bunker-crescent' | 'bunker-pot'
  | 'water-pond' | 'water-creek'
  | 'path-stub' | 'road-stub';

/** 2D point in world tiles (2 m per tile) */
export interface SnapPt { x: number; y: number }

/** unit sun direction in world tiles for sun on the right of the isometric screen (+screenX = +tileX - tileY) */
export const SUN_RIGHT_TILE_VEC: Readonly<SnapPt> = { x: 0.70710678, y: -0.70710678 };

/** existing course area that a new modular piece can snap against */
export interface SnapTargetArea { id: number; kind: SnapPieceKind; pts: readonly number[]; hole?: number }

/** existing road segment that a cart path or road stub can snap against */
export interface SnapTargetRoad { id: number; ax: number; ay: number; bx: number; by: number; halfWidthTiles: number }

/** one concentric PaintArea layer generated by a modular piece (shadow-bevel -> outer-rim -> sun-bevel -> collar -> core -> join-apron) */
export interface CoursePieceLayer {
  role: 'turf-base' | 'outer-rim' | 'sun-bevel' | 'shadow-bevel' | 'collar' | 'core' | 'join-apron';
  kind: 'rough' | 'water' | 'fairway' | 'tee' | 'bunker' | 'green' | 'path';
  tex: string;
  border: 0 | 1 | 2 | 3;
  btex: string;
  radius: number;
  angle: number;
  tone?: 0 | 1 | 2;
  toneAmt?: number;
  tint?: string;
  pts: number[];
}

/** automatic 3D height sculpt operation emitted when a piece is placed (feeds applyCourseHeightBrush in T026) */
export interface CoursePieceHeightOp { x: number; y: number; radiusTiles: number; mode: 'raise' | 'lower' | 'smooth' | 'flatten'; strength: number }

/** automatic prop or hole marker anchor emitted with a modular piece (tee steps, tee markers, pins, pond rocks/reeds/waterfall) */
export interface CoursePiecePropAnchor {
  kind: 'pin' | 'practice-pin' | 'tee-back' | 'tee-middle' | 'tee-forward' | 'tee-steps' | 'bunker-rake' | 'pond-waterfall' | 'pond-rock' | 'pond-reeds';
  x: number;
  y: number;
  angleDeg: number;
  number?: number;
}

/** auto-texture and collar trim recipe applied when a snapped piece is placed (Owner choice 3A) */
export interface AutoTextureRecipe { tex: string; border: 0 | 1 | 2 | 3; btex: string; radius: number; angle: number; joinCollarPts?: number[]; joinCollarTex?: string }

/** complete result of evaluating a modular course or road piece at cursor (x, y) */
export interface SnapPiecePlacement {
  kind: SnapPieceKind;
  archetype: CoursePieceArchetype;
  pts: number[];
  layers: CoursePieceLayer[];
  heightOps: CoursePieceHeightOp[];
  props: CoursePiecePropAnchor[];
  anchor: SnapPt;
  angleDeg: number;
  snapped: boolean;
  snapRule: 'none' | 'fairway-to-fairway' | 'fairway-to-green' | 'green-to-fairway' | 'tee-to-fairway' | 'bunker-to-green' | 'water-to-water' | 'path-to-road' | 'road-to-road';
  targetId: number;
  snapPt?: SnapPt;
  snapNormal?: SnapPt;
  hole: number;
  recipe: AutoTextureRecipe;
}

/** options for computing a snapped modular piece placement */
export interface SnapPieceOptions {
  kind: SnapPieceKind;
  archetype?: CoursePieceArchetype;
  cursor: SnapPt;
  angleDeg?: number;
  scale?: number;
  snapEnabled?: boolean;
  snapRadiusTiles?: number;
  defaultHole?: number;
  areas?: readonly SnapTargetArea[];
  roads?: readonly SnapTargetRoad[];
}

/** default dimensions (length along heading, width across heading, in tiles of 2 m) for each piece kind */
export const SNAP_PIECE_DIMS: Record<SnapPieceKind, { lengthTiles: number; widthTiles: number }> = {
  fairway: { lengthTiles: 24, widthTiles: 12 },
  green: { lengthTiles: 11, widthTiles: 9 },
  tee: { lengthTiles: 6, widthTiles: 4 },
  bunker: { lengthTiles: 6, widthTiles: 4.5 },
  water: { lengthTiles: 12, widthTiles: 9 },
  path: { lengthTiles: 14, widthTiles: 2 },
  road: { lengthTiles: 16, widthTiles: 4 },
};

const q4 = (v: number) => Math.round(v * 4) / 4 + 0;

/** wraps an angle in degrees into [-90, 90] matching wrapAngle in src/game/paint.ts */
export function wrapPaintAngle(deg: number): number {
  if (!Number.isFinite(deg)) return 0;
  return deg >= -90 && deg <= 90 ? deg + 0 : ((((deg + 90) % 180) + 180) % 180) - 90 + 0;
}

/** maps a SnapPieceKind to its default CoursePieceArchetype when none is specified */
export function defaultArchetypeForKind(kind: SnapPieceKind): CoursePieceArchetype {
  return kind === 'fairway' ? 'fairway-pear' : kind === 'green' ? 'green-kidney' : kind === 'tee' ? 'tee-raised' : kind === 'bunker' ? 'bunker-crescent' : kind === 'water' ? 'water-pond' : kind === 'path' ? 'path-stub' : 'road-stub';
}

/** returns the auto-texture and collar recipe for a piece kind and heading angle (Owner choice 3A) */
export function autoTextureForPiece(
  kind: SnapPieceKind,
  angleDeg: number,
  snapRule: SnapPiecePlacement['snapRule'] = 'none',
  snapPt?: SnapPt,
  snapNormal?: SnapPt,
): AutoTextureRecipe {
  const angle = wrapPaintAngle(angleDeg);
  const base: AutoTextureRecipe =
    kind === 'fairway' ? { tex: 'golfFairway', border: 3, btex: 'golfFirstCut', radius: 3, angle }
    : kind === 'green' ? { tex: 'golfGreen', border: 2, btex: 'golfFringe', radius: 4, angle }
    : kind === 'tee' ? { tex: 'golfTee', border: 1, btex: 'golfFirstCut', radius: 1, angle }
    : kind === 'bunker' ? { tex: 'bunkerSand', border: 2, btex: 'golfRough', radius: 2, angle }
    : kind === 'water' ? { tex: 'waterClear', border: 2, btex: 'rockyDirt', radius: 3, angle }
    : kind === 'path' ? { tex: 'spectatorPath', border: 1, btex: 'gravel', radius: 0, angle }
    : { tex: 'asphalt', border: 1, btex: 'kerb', radius: 0, angle };
  if ((snapRule === 'path-to-road' || snapRule === 'road-to-road') && snapPt && snapNormal) {
    const hw = kind === 'path' ? 1.5 : 2.5, depth = 1.5, nx = snapNormal.x, ny = snapNormal.y, tx = -ny, ty = nx;
    const ax = snapPt.x, ay = snapPt.y, bx = ax + nx * depth, by = ay + ny * depth;
    base.joinCollarPts = [q4(ax + tx * hw), q4(ay + ty * hw), q4(bx + tx * hw), q4(by + ty * hw), q4(bx - tx * hw), q4(by - ty * hw), q4(ax - tx * hw), q4(ay - ty * hw)];
    base.joinCollarTex = snapRule === 'path-to-road' ? 'gravel' : 'kerb';
  } else if ((snapRule === 'fairway-to-green' || snapRule === 'green-to-fairway') && snapPt && snapNormal) {
    const hw = 4, depth = 2, nx = snapNormal.x, ny = snapNormal.y, tx = -ny, ty = nx;
    const ax = snapPt.x - nx * 0.5, ay = snapPt.y - ny * 0.5, bx = snapPt.x + nx * depth, by = snapPt.y + ny * depth;
    base.joinCollarPts = [q4(ax + tx * hw), q4(ay + ty * hw), q4(bx + tx * hw), q4(by + ty * hw), q4(bx - tx * hw), q4(by - ty * hw), q4(ax - tx * hw), q4(ay - ty * hw)];
    base.joinCollarTex = 'golfFringe';
  }
  return base;
}

/** builds a variable-width curved spline ribbon (for dogleg fairways and meandering creeks) from start -> control -> end */
export function buildSplineRibbonPolygon(start: SnapPt, control: SnapPt, end: SnapPt, startHalfWidth: number, endHalfWidth: number, steps = 10, bulgeMid = 1.15): number[] {
  const n = Math.max(4, Math.min(24, Math.round(steps))), left: SnapPt[] = [], right: SnapPt[] = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n, u = 1 - t;
    const x = u * u * start.x + 2 * u * t * control.x + t * t * end.x, y = u * u * start.y + 2 * u * t * control.y + t * t * end.y;
    const dx = 2 * u * (control.x - start.x) + 2 * t * (end.x - control.x), dy = 2 * u * (control.y - start.y) + 2 * t * (end.y - control.y);
    const len = Math.hypot(dx, dy) || 1, nx = -dy / len, ny = dx / len;
    const hw = (startHalfWidth + (endHalfWidth - startHalfWidth) * t) * (1 + (bulgeMid - 1) * Math.sin(Math.PI * t));
    left.push({ x: q4(x + nx * hw), y: q4(y + ny * hw) });
    right.push({ x: q4(x - nx * hw), y: q4(y - ny * hw) });
  }
  const out: number[] = [];
  for (const p of left) out.push(p.x, p.y);
  for (let i = right.length - 1; i >= 0; i--) out.push(right[i]!.x, right[i]!.y);
  return out;
}

/** expands or shrinks a closed polygon radially from its centroid by padTiles, with an optional directional shift (dx, dy) */
export function offsetPolygonRadial(pts: readonly number[], padTiles: number, shiftX = 0, shiftY = 0): number[] {
  const n = pts.length >> 1;
  if (n < 3) return pts.slice();
  let cx = 0, cy = 0;
  for (let i = 0; i < n; i++) { cx += pts[2 * i]!; cy += pts[2 * i + 1]!; }
  cx /= n; cy /= n;
  const out: number[] = [];
  for (let i = 0; i < n; i++) {
    const dx = pts[2 * i]! - cx, dy = pts[2 * i + 1]! - cy, r = Math.hypot(dx, dy) || 1, nr = Math.max(0.5, r + padTiles);
    out.push(q4(cx + (dx / r) * nr + shiftX), q4(cy + (dy / r) * nr + shiftY));
  }
  return out;
}

/** builds sun-on-the-right lit and shaded bevel polygons for raised (tee/green/fairway) or sunken (bunker/pond) pieces */
export function buildSunRightBevelPolygons(pts: readonly number[], elevationMode: 'raised' | 'sunken', bevelTiles = 0.75): { sunLitPts: number[]; shadedPts: number[] } {
  const sx = SUN_RIGHT_TILE_VEC.x * bevelTiles, sy = SUN_RIGHT_TILE_VEC.y * bevelTiles;
  return elevationMode === 'raised'
    ? { sunLitPts: offsetPolygonRadial(pts, bevelTiles * 0.4, sx * 0.6, sy * 0.6), shadedPts: offsetPolygonRadial(pts, bevelTiles * 0.6, -sx, -sy) }
    : { sunLitPts: offsetPolygonRadial(pts, bevelTiles * 0.35, -sx * 0.7, -sy * 0.7), shadedPts: offsetPolygonRadial(pts, bevelTiles * 0.35, sx * 0.7, sy * 0.7) };
}

/** builds the organic polygon for an archetype in world tiles, plus its centre and unit basis */
export function buildArchetypePolygon(archetype: CoursePieceArchetype, anchor: SnapPt, angleDeg: number, scale = 1, endAnchored = false): { pts: number[]; center: SnapPt; ux: number; uy: number; nx: number; ny: number; L: number; W: number } {
  const s = Math.max(0.5, Math.min(2.5, Number.isFinite(scale) ? scale : 1));
  const kind: SnapPieceKind = archetype.startsWith('green') ? 'green' : archetype.startsWith('tee') ? 'tee' : archetype.startsWith('bunker') ? 'bunker' : archetype.startsWith('water') ? 'water' : archetype.startsWith('path') ? 'path' : archetype.startsWith('road') ? 'road' : 'fairway';
  const dims = SNAP_PIECE_DIMS[kind], L = dims.lengthTiles * s, W = dims.widthTiles * s;
  const rad = (angleDeg * Math.PI) / 180, ux = Math.cos(rad), uy = Math.sin(rad), nx = -uy, ny = ux;
  const cx = endAnchored ? anchor.x + ux * (L / 2) : anchor.x, cy = endAnchored ? anchor.y + uy * (L / 2) : anchor.y;
  const toWorld = (lx: number, ly: number): SnapPt => ({ x: q4(cx + ux * lx + nx * ly), y: q4(cy + uy * lx + ny * ly) });
  if (archetype === 'green-kidney' || archetype === 'green-peanut' || archetype === 'green-practice' || archetype === 'bunker-crescent' || archetype === 'bunker-pot' || archetype === 'water-pond') {
    const out: number[] = [], steps = archetype === 'bunker-pot' ? 12 : 16, rx = archetype === 'bunker-pot' ? Math.min(L, W) * 0.48 : L / 2, ry = archetype === 'bunker-pot' ? rx : W / 2;
    for (let k = 0; k < steps; k++) {
      const a = (k * 2 * Math.PI) / steps, ca = Math.cos(a), sa = Math.sin(a);
      if (archetype === 'bunker-crescent') {
        const indent = sa > 0 ? 1 - 0.42 * sa : 1 - 0.15 * sa;
        const p = toWorld(ca * rx, sa * ry * indent + ca * ca * 0.25 * ry);
        out.push(p.x, p.y);
      } else {
        const mod = archetype === 'green-kidney' ? 1 + 0.18 * Math.cos(2 * a) - 0.22 * Math.max(0, sa)
          : archetype === 'green-peanut' ? 1 + 0.28 * Math.cos(2 * a)
          : archetype === 'green-practice' ? 1 + 0.16 * Math.cos(3 * a)
          : archetype === 'water-pond' ? 1 + 0.18 * Math.sin(2 * a) + 0.1 * Math.cos(3 * a) : 1;
        const p = toWorld(ca * rx * mod, sa * ry * mod);
        out.push(p.x, p.y);
      }
    }
    return { pts: out, center: { x: q4(cx), y: q4(cy) }, ux, uy, nx, ny, L, W };
  }
  if (archetype === 'water-creek' || archetype === 'fairway-dogleg-left' || archetype === 'fairway-dogleg-right' || archetype === 'fairway-pear') {
    const bend = archetype === 'fairway-dogleg-left' ? -1 : archetype === 'fairway-dogleg-right' ? 1 : archetype === 'water-creek' ? 0.6 : 0;
    const p0 = toWorld(-L / 2, 0), ctrl = toWorld(0, bend * W * 0.45), p1 = toWorld(L / 2, bend * W * 0.7);
    const hw0 = archetype === 'water-creek' ? W * 0.22 : archetype === 'fairway-pear' ? W * 0.34 : W * 0.42;
    const hw1 = archetype === 'water-creek' ? W * 0.28 : archetype === 'fairway-pear' ? W * 0.58 : W * 0.52;
    return { pts: buildSplineRibbonPolygon(p0, ctrl, p1, hw0, hw1, 10, archetype === 'fairway-pear' ? 1.2 : 1.08), center: { x: q4(cx), y: q4(cy) }, ux, uy, nx, ny, L, W };
  }
  const hw = W / 2, x0 = cx - ux * (L / 2), y0 = cy - uy * (L / 2), x1 = cx + ux * (L / 2), y1 = cy + uy * (L / 2);
  const pts = [q4(x0 + nx * hw), q4(y0 + ny * hw), q4(x1 + nx * hw), q4(y1 + ny * hw), q4(x1 - nx * hw), q4(y1 - ny * hw), q4(x0 - nx * hw), q4(y0 - ny * hw)];
  return { pts, center: { x: q4(cx), y: q4(cy) }, ux, uy, nx, ny, L, W };
}

/** backward-compatible helper returning the primary polygon for a SnapPieceKind */
export function buildPiecePolygon(kind: SnapPieceKind, anchor: SnapPt, angleDeg: number, scale = 1, endAnchored = false): number[] {
  const arch: CoursePieceArchetype = kind === 'fairway' ? 'fairway-corridor' : defaultArchetypeForKind(kind);
  return buildArchetypePolygon(arch, anchor, angleDeg, scale, endAnchored).pts;
}

/** builds the multi-layer concentric PaintArea stack (with fat grass borders + sun-from-right 3D bevels), height ops, and prop anchors */
function buildRichPieceStack(kind: SnapPieceKind, archetype: CoursePieceArchetype, corePts: number[], center: SnapPt, ux: number, uy: number, nx: number, ny: number, L: number, W: number, angleDeg: number, recipe: AutoTextureRecipe): { layers: CoursePieceLayer[]; heightOps: CoursePieceHeightOp[]; props: CoursePiecePropAnchor[] } {
  const angle = recipe.angle, layers: CoursePieceLayer[] = [], heightOps: CoursePieceHeightOp[] = [], props: CoursePiecePropAnchor[] = [];
  const toWorld = (lx: number, ly: number): SnapPt => ({ x: q4(center.x + ux * lx + nx * ly), y: q4(center.y + uy * lx + ny * ly) });
  const mk = (role: CoursePieceLayer['role'], k: CoursePieceLayer['kind'], tex: string, border: 0 | 1 | 2 | 3, btex: string, radius: number, pts: number[], tone?: 0 | 1 | 2, toneAmt?: number, tint?: string): CoursePieceLayer =>
    ({ role, kind: k, tex, border, btex, radius, angle, pts, ...(tone ? { tone, toneAmt, tint } : {}) });
  const pushPt = (k: CoursePiecePropAnchor['kind'], lx: number, ly: number, a = angleDeg, n?: number) => { const p = toWorld(lx, ly); props.push({ kind: k, x: p.x, y: p.y, angleDeg: a, ...(n ? { number: n } : {}) }); };
  if (kind === 'green') {
    const outR = offsetPolygonRadial(corePts, 2.5), bev = buildSunRightBevelPolygons(outR, 'raised', 0.65);
    layers.push(mk('shadow-bevel', 'rough', 'golfRough', 3, 'barkMulch', 4, bev.shadedPts, 1, 0.45, '#141a0a'), mk('outer-rim', 'rough', 'golfRough', 3, 'pineStraw', 4, outR), mk('sun-bevel', 'rough', 'golfFirstCut', 2, 'golfRough', 4, bev.sunLitPts, 2, 0.28, '#d9f99d'), mk('collar', 'fairway', 'golfFringe', 3, 'golfFirstCut', 4, offsetPolygonRadial(corePts, 1.25)), mk('core', 'green', recipe.tex, 3, recipe.btex, recipe.radius, corePts));
    heightOps.push({ x: q4(center.x + ux * (L * 0.18)), y: q4(center.y + uy * (L * 0.18)), radiusTiles: Math.max(4, Math.round(L * 0.45)), mode: 'raise', strength: 0.35 });
    if (archetype === 'green-practice') { pushPt('practice-pin', -L * 0.2, -W * 0.15, 0, 1); pushPt('practice-pin', 0.05 * L, W * 0.22, 0, 2); pushPt('practice-pin', L * 0.24, -W * 0.1, 0, 3); }
    else pushPt('pin', L * 0.15, 0, 0);
  } else if (kind === 'tee') {
    const outR = offsetPolygonRadial(corePts, 2.0), bev = buildSunRightBevelPolygons(outR, 'raised', 0.9);
    layers.push(mk('shadow-bevel', 'rough', 'golfRough', 3, 'barkMulch', 2, bev.shadedPts, 1, 0.52, '#121809'), mk('outer-rim', 'rough', 'golfRough', 3, 'barkMulch', 2, outR), mk('sun-bevel', 'fairway', 'golfFirstCut', 2, 'golfRough', 2, bev.sunLitPts, 2, 0.32, '#ecfccb'), mk('collar', 'fairway', 'golfFirstCut', 2, 'golfFringe', 1.5, offsetPolygonRadial(corePts, 0.85)), mk('core', 'tee', recipe.tex, 2, recipe.btex, recipe.radius, corePts));
    if (archetype === 'tee-raised') { heightOps.push({ x: center.x, y: center.y, radiusTiles: Math.max(4, Math.round(Math.max(L, W) * 0.85)), mode: 'raise', strength: 0.95 }); pushPt('tee-steps', 0, -W * 0.65, (angleDeg - 90 + 360) % 360); }
    pushPt('tee-back', -L * 0.25, 0); pushPt('tee-middle', 0, 0); pushPt('tee-forward', L * 0.25, 0);
  } else if (kind === 'fairway') {
    const outR = offsetPolygonRadial(corePts, 2.5), bev = buildSunRightBevelPolygons(outR, 'raised', 0.55);
    layers.push(mk('shadow-bevel', 'rough', 'golfRough', 3, 'pineStraw', 3, bev.shadedPts, 1, 0.38, '#141b0b'), mk('outer-rim', 'rough', 'golfRough', 3, 'golfFirstCut', 3, outR), mk('collar', 'fairway', 'golfFirstCut', 3, 'golfFringe', 3, offsetPolygonRadial(corePts, 1.2)), mk('core', 'fairway', recipe.tex, 3, recipe.btex, recipe.radius, corePts));
  } else if (kind === 'bunker') {
    const outR = offsetPolygonRadial(corePts, 1.75), bev = buildSunRightBevelPolygons(corePts, 'sunken', 0.85);
    layers.push(mk('outer-rim', 'rough', 'golfRough', 3, 'rockyDirt', 2, outR), mk('shadow-bevel', 'bunker', 'rockyDirt', 3, 'barkMulch', 2, bev.shadedPts, 1, 0.55, '#1c140d'), mk('sun-bevel', 'bunker', 'wasteSand', 2, 'rockyDirt', 2, bev.sunLitPts, 2, 0.3, '#fef3c7'), mk('core', 'bunker', recipe.tex, 3, recipe.btex, recipe.radius, corePts));
    heightOps.push({ x: center.x, y: center.y, radiusTiles: Math.max(3, Math.round(Math.max(L, W) * 0.6)), mode: 'lower', strength: archetype === 'bunker-pot' ? 0.9 : 0.65 }, { x: q4(center.x + ux * (L * 0.35)), y: q4(center.y + uy * (L * 0.35)), radiusTiles: Math.max(2, Math.round(W * 0.5)), mode: 'raise', strength: 0.45 });
    pushPt('bunker-rake', -L * 0.15, -W * 0.1);
  } else if (kind === 'water') {
    const outR = offsetPolygonRadial(corePts, 2.0), bev = buildSunRightBevelPolygons(corePts, 'sunken', 0.7);
    layers.push(mk('outer-rim', 'rough', 'meadowFlowers', 3, 'golfRough', 3, outR), mk('shadow-bevel', 'water', 'rockyDirt', 3, 'barkMulch', 3, bev.shadedPts, 1, 0.48, '#0f172a'), mk('collar', 'water', 'rockyDirt', 2, 'gravel', 3, offsetPolygonRadial(corePts, 0.85)), mk('core', 'water', recipe.tex, 3, recipe.btex, recipe.radius, corePts));
    heightOps.push({ x: center.x, y: center.y, radiusTiles: Math.max(4, Math.round(Math.max(L, W) * 0.65)), mode: 'lower', strength: 0.6 });
    pushPt('pond-waterfall', -L * 0.42, 0); pushPt('pond-rock', L * 0.38, W * 0.28); pushPt('pond-reeds', -L * 0.1, -W * 0.42, 0);
  } else {
    layers.push(mk('core', 'path', recipe.tex, recipe.border, recipe.btex, recipe.radius, corePts));
  }
  // the join strip's edge: a kerb only where a road meets a road, gravel at a cart path, first cut where turf meets turf (a kerb there read as a pale ring on the course)
  if (recipe.joinCollarPts && recipe.joinCollarTex) layers.push(mk('join-apron', kind === 'path' || kind === 'road' ? 'path' : 'fairway', recipe.joinCollarTex, 2, kind === 'road' ? 'kerb' : kind === 'path' ? 'gravel' : 'golfFirstCut', 1, recipe.joinCollarPts));
  return { layers, heightOps, props };
}

/** finds the closest point and outward unit normal on polygon pts to point p */
function closestPolyEdge(pts: readonly number[], p: SnapPt): { pt: SnapPt; normal: SnapPt; dist: number } | null {
  const n = pts.length >> 1;
  if (n < 3) return null;
  let area2 = 0;
  for (let i = 0; i < n; i++) { const j = (i + 1) % n; area2 += pts[2 * i]! * pts[2 * j + 1]! - pts[2 * j]! * pts[2 * i + 1]!; }
  const ccw = area2 >= 0 ? 1 : -1;
  let bestDist = Infinity, bestPt: SnapPt = { x: p.x, y: p.y }, bestN: SnapPt = { x: 1, y: 0 };
  for (let i = 0; i < n; i++) {
    const j = (i + 1) % n, ax = pts[2 * i]!, ay = pts[2 * i + 1]!, bx = pts[2 * j]!, by = pts[2 * j + 1]!;
    const dx = bx - ax, dy = by - ay, len2 = dx * dx + dy * dy;
    if (len2 < 1e-9) continue;
    const t = Math.max(0, Math.min(1, ((p.x - ax) * dx + (p.y - ay) * dy) / len2));
    const qx = ax + dx * t, qy = ay + dy * t, d = Math.hypot(p.x - qx, p.y - qy);
    if (d < bestDist) { const len = Math.sqrt(len2); bestDist = d; bestPt = { x: q4(qx), y: q4(qy) }; bestN = { x: (dy / len) * ccw + 0, y: (-dx / len) * ccw + 0 }; }
  }
  return bestDist < Infinity ? { pt: bestPt, normal: bestN, dist: bestDist } : null;
}

function matchAreaSnapRule(piece: SnapPieceKind, target: SnapPieceKind): SnapPiecePlacement['snapRule'] {
  return piece === 'fairway' && target === 'fairway' ? 'fairway-to-fairway'
    : piece === 'fairway' && target === 'green' ? 'fairway-to-green'
    : piece === 'green' && target === 'fairway' ? 'green-to-fairway'
    : piece === 'tee' && target === 'fairway' ? 'tee-to-fairway'
    : piece === 'bunker' && target === 'green' ? 'bunker-to-green'
    : piece === 'water' && target === 'water' ? 'water-to-water' : 'none';
}

/** computes the snapped or freehand placement, fat grass border layers, sun-right bevels, height ops, and prop anchors */
export function computeSnapPiecePlacement(opts: SnapPieceOptions): SnapPiecePlacement {
  const kind = opts.kind, scale = Math.max(0.5, Math.min(2.5, Number.isFinite(opts.scale) ? opts.scale! : 1));
  const userAngle = Number.isFinite(opts.angleDeg) ? opts.angleDeg! : 0, snapOn = opts.snapEnabled !== false;
  const radius = Math.max(1, Number.isFinite(opts.snapRadiusTiles) ? opts.snapRadiusTiles! : 6), defaultHole = Math.max(1, Math.min(18, Math.round(opts.defaultHole ?? 1)));
  let bestDist = radius, snapRule: SnapPiecePlacement['snapRule'] = 'none', targetId = 0, snapPt: SnapPt | undefined, snapNormal: SnapPt | undefined, hole = defaultHole;
  if (snapOn) {
    if ((kind === 'path' || kind === 'road') && opts.roads) {
      for (const r of opts.roads) {
        const dx = r.bx - r.ax, dy = r.by - r.ay, len2 = dx * dx + dy * dy;
        if (len2 < 1e-9) continue;
        const t = Math.max(0, Math.min(1, ((opts.cursor.x - r.ax) * dx + (opts.cursor.y - r.ay) * dy) / len2));
        const cx = r.ax + dx * t, cy = r.ay + dy * t, vx = opts.cursor.x - cx, vy = opts.cursor.y - cy, centerDist = Math.hypot(vx, vy), len = Math.sqrt(len2);
        let nx = -dy / len, ny = dx / len;
        if (vx * nx + vy * ny < 0) { nx = -nx; ny = -ny; }
        const distToKerb = Math.abs(centerDist - r.halfWidthTiles);
        if (distToKerb <= bestDist) {
          bestDist = distToKerb; snapRule = kind === 'path' ? 'path-to-road' : 'road-to-road'; targetId = r.id;
          snapPt = { x: q4(cx + nx * r.halfWidthTiles), y: q4(cy + ny * r.halfWidthTiles) }; snapNormal = { x: nx + 0, y: ny + 0 };
        }
      }
    }
    if (opts.areas) {
      for (const a of opts.areas) {
        const rule = matchAreaSnapRule(kind, a.kind);
        if (rule === 'none') continue;
        const hit = closestPolyEdge(a.pts, opts.cursor);
        if (hit && hit.dist <= bestDist) {
          bestDist = hit.dist; snapRule = rule; targetId = a.id; snapPt = hit.pt; snapNormal = hit.normal;
          if (a.hole && a.hole >= 1 && a.hole <= 18) hole = a.hole;
        }
      }
    }
  }
  const snapped = snapRule !== 'none' && snapPt !== undefined && snapNormal !== undefined;
  const angleDeg = snapped ? Math.round((Math.atan2(snapNormal!.y, snapNormal!.x) * 180) / Math.PI) + 0 : userAngle;
  const anchor = snapped ? snapPt! : { x: q4(opts.cursor.x), y: q4(opts.cursor.y) };
  const effectiveArch: CoursePieceArchetype = opts.archetype ?? (kind === 'fairway' ? 'fairway-corridor' : defaultArchetypeForKind(kind));
  const built = buildArchetypePolygon(effectiveArch, anchor, angleDeg, scale, snapped);
  const recipe = autoTextureForPiece(kind, angleDeg, snapRule, snapPt, snapNormal);
  const stack = buildRichPieceStack(kind, effectiveArch, built.pts, built.center, built.ux, built.uy, built.nx, built.ny, built.L, built.W, angleDeg, recipe);
  return { kind, archetype: effectiveArch, pts: built.pts, layers: stack.layers, heightOps: stack.heightOps, props: stack.props, anchor, angleDeg, snapped, snapRule, targetId, ...(snapPt ? { snapPt } : {}), ...(snapNormal ? { snapNormal } : {}), hole, recipe };
}
