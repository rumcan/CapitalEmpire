export interface Box { hx: number; hy: number; dx: number; dy: number }
export interface Glow { x: number; y: number; r: number }

/** A library sprite (from the Maple Falls town builder export). */
export interface LibItem {
  id: string;
  name: string;
  cat: string;
  kind: string;
  /** display size in world px at the native 128 px-per-tile scale */
  w: number;
  h: number;
  /** anchor (the ground point) inside the display rectangle */
  ax: number;
  ay: number;
  /** footprint boxes in metres (2 m per tile) around the anchor */
  boxes: Box[];
  /** a baked lot (kind 'lot'): the house's footprint, drawn as its building block on the planner map (boxes cover the whole lot) */
  block?: Box;
  solid: number;
  big: boolean;
  door: boolean;
  doorAt?: { u: number; v: number };
  cost: number;
  glows?: Glow[];
  /** a baked lot's night lights (its house's porch, pumpkins, lanterns...): metres from the anchor, unscaled and unmirrored, and the light type (night-light.ts) */
  lights?: { dx: number; dy: number; type: string }[];
  /** atlas page and UVs: [page, u0, v0, u1, v1] */
  tex: [number, number, number, number, number];
  /** the trimmed picture inside the w x h display rectangle: [x0, y0, x1, y1] display px */
  quad: [number, number, number, number];
}

export interface Prop {
  uid: number;
  /** drawn tinted (T176: a tree New hole's Build would clear; sprites.ts Drawable.tint) */
  tint?: boolean;
  /** index into LIBRARY */
  item: number;
  x: number;
  y: number;
  flip: boolean;
  scale: number;
  /** footprint in tiles (derived) */
  x0: number;
  y0: number;
  x1: number;
  y1: number;
  /** generated by the road network (median trees, traffic lights); regenerated, never saved */
  auto?: string;
  /** placed by a plant brush (Paint: Trees, Bushes, Flowers): its Rub out removes it, and it is free (no refund); saved as the tuple's 6th element */
  plant?: 1;
  /** placed by the Props tool (T131): its catalogue key (golf/decor.ts); saved as the tuple's 7th element (the 6th is then 0) */
  decor?: string;
  /** T229: a frame tree (golf/holeframe.ts, Frame with trees): the hole it frames; saved as the tuple's 8th element, after its catalogue key */
  frame?: number;
  /** drawn this high above its spot (world px; T133: the range's upper deck, an auto prop, never saved): sprites.ts Drawable.lift */
  lift?: number;
}

/** path: the rail's Paths (T084), the road tool on the course's cart paths and drives (setTool turns it into 'road' with roadScope 'course');
 *  buildings: the rail's Buildings (plan P23 P1-E), the course tool in its buildings scope, which places the clubhouse (setTool turns it into
 *  'course' with courseScope 'buildings'); props: the rail's Props (T131, golf/propstool.ts), the course's decor */
export type Tool = 'select' | 'road' | 'junction' | 'bulldoze' | 'park' | 'toll' | 'bus' | 'lane' | 'downgrade' | 'business' | 'paint' | 'course' | 'path' | 'buildings' | 'props' | 'greenkeeping' | 'practice';
export type LineStyle = 0 | 1 | 2; // 0 dashed single, 1 double solid, 2 none
export type BendMode = 90 | 45;

export interface SaveData {
  version: number;
  /** map seed (terrain generation, later phases) */
  seed?: number;
  map: number;
  terrain: string;
  /** ax, ay, bx, by, class, line style */
  segs: [number, number, number, number, string, number][];
  /** x, y, junction type */
  nodes: [number, number, string][];
  props: [number, number, number, number, number][]; // item, x, y, flip, scale
  money: number;
  day: number;
  cam?: { X: number; Y: number; z: number };
}
